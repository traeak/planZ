//! Kernel errors.
//! from 9/port/error.h; the strings are what mkerrstr makes of its comments.
//!
//! DIFF: the C kernel unwinds with error(Estr)/waserror()/nexterror(),
//! a longjmp through up->errlab.  Here a failing function returns a Zig
//! error and callers clean up with defer and errdefer.  Each E-string
//! is an error tag; `errstr` gives its text, which is what user programs
//! see.  A message built at run time goes in up.errstr and is returned
//! as error.Str (see proc.zig, `errorf`).

pub const Error = error{
    Enoerror,
    Emount,
    Eunmount,
    Eismtpt,
    Eunion,
    Emountrpc,
    Eshutdown,
    Enocreate,
    Enonexist,
    Eexist,
    Ebadsharp,
    Enotdir,
    Eisdir,
    Ebadchar,
    Efilename,
    Eperm,
    Ebadusefd,
    Ebadarg,
    Einuse,
    Eio,
    Etoobig,
    Etoosmall,
    Enoport,
    Ehungup,
    Ebadctl,
    Enodev,
    Eprocdied,
    Enochild,
    Eioload,
    Enovmem,
    Ebadfd,
    Enofd,
    Eisstream,
    Ebadexec,
    Etimedout,
    Econrefused,
    Econinuse,
    Eintr,
    Enomem,
    Esoverlap,
    Emouseset,
    Eshort,
    Egreg,
    Ebadspec,
    Enoreg,
    Enoattach,
    Eshortstat,
    Ebadstat,
    Enegoff,
    Ecmdargs,
    Ebadip,
    Edirseek,
    Etoolong,
    Echange,
    Emsize,
    /// The text is in up.errstr.
    Str,
};

/// The message for an error, as error(Estr) would have set it.
/// For error.Str the caller must look in up.errstr.
pub fn errstr(e: Error) []const u8 {
    return switch (e) {
        error.Enoerror => "no error",
        error.Emount => "inconsistent mount",
        error.Eunmount => "not mounted",
        error.Eismtpt => "is a mount point",
        error.Eunion => "not in union",
        error.Emountrpc => "mount rpc error",
        error.Eshutdown => "device shut down",
        error.Enocreate => "mounted directory forbids creation",
        error.Enonexist => "file does not exist",
        error.Eexist => "file already exists",
        error.Ebadsharp => "unknown device in # filename",
        error.Enotdir => "not a directory",
        error.Eisdir => "file is a directory",
        error.Ebadchar => "bad character in file name",
        error.Efilename => "file name syntax",
        error.Eperm => "permission denied",
        error.Ebadusefd => "inappropriate use of fd",
        error.Ebadarg => "bad arg in system call",
        error.Einuse => "device or object already in use",
        error.Eio => "i/o error",
        error.Etoobig => "read or write too large",
        error.Etoosmall => "read or write too small",
        error.Enoport => "network port not available",
        error.Ehungup => "i/o on hungup channel",
        error.Ebadctl => "bad process or channel control request",
        error.Enodev => "no free devices",
        error.Eprocdied => "process exited",
        error.Enochild => "no living children",
        error.Eioload => "i/o error in demand load",
        error.Enovmem => "virtual memory allocation failed",
        error.Ebadfd => "fd out of range or not open",
        error.Enofd => "no free file descriptors",
        error.Eisstream => "seek on a stream",
        error.Ebadexec => "exec header invalid",
        error.Etimedout => "connection timed out",
        error.Econrefused => "connection refused",
        error.Econinuse => "connection in use",
        error.Eintr => "interrupted",
        error.Enomem => "kernel allocate failed",
        error.Esoverlap => "segments overlap",
        error.Emouseset => "mouse type already set",
        error.Eshort => "i/o count too small",
        error.Egreg => "the front fell off",
        error.Ebadspec => "bad attach specifier",
        error.Enoreg => "process has no saved registers",
        error.Enoattach => "mount/attach disallowed",
        error.Eshortstat => "stat buffer too small",
        error.Ebadstat => "malformed stat buffer",
        error.Enegoff => "negative i/o offset",
        error.Ecmdargs => "wrong #args in control message",
        error.Ebadip => "bad ip address syntax",
        error.Edirseek => "seek in directory",
        error.Etoolong => "name too long",
        error.Echange => "media or partition has changed",
        error.Emsize => "message size too small",
        error.Str => "",
    };
}
